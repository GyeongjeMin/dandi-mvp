/** 기억에 다른 분류의 지역 태그가 있으면 "진주에서 " 같은 말머리를 붙입니다. */
function placePrefix(m: Memory): string {
  if (m.category === 'place') return '';
  const p = m.tags.find((t) => getTagDef(t)?.category === 'place');
  return p ? `${p}에서 ` : '';
}

function generic(m: Memory, variant: number): string {
  const t = m.title;
  const lists: Record<Memory['category'], string[]> = {
    work: [
      `전에 ${eul(t)} 하셨다고 말씀하셨죠. 그 일을 하시면서 가장 보람 있었던 순간은 언제였나요?`,
      `${t} 일을 하시던 시절, 함께 일하던 분들 중에 생각나는 분이 있으세요?`,
    ],
    hobby: [
      `전에 ${eul(t)} 좋아하신다고 하셨죠. 요즘도 즐겨 하세요?`,
      `${eul(t)} 처음 좋아하게 된 계기가 있으셨어요?`,
    ],
    place: [
      `전에 ${t} 이야기를 해 주셨죠. 그곳 하면 가장 먼저 떠오르는 풍경이 있으세요?`,
      `${t} 시절에 자주 가시던 단골집이나 장소가 있으셨어요?`,
    ],
    family: [
      `전에 ${t.replace(/^가족 이야기 — /, '')} 이야기를 해 주셨죠. 함께한 기억 중 가장 따뜻했던 순간은 언제였어요?`,
    ],
    life_event: [
      `전에 ${t} 이야기를 해 주셨죠. 그때를 떠올리면 어떤 마음이 드세요?`,
      `${t} 무렵에 가장 힘이 되어 준 사람은 누구였어요?`,
    ],
    daily: [
      `전에 ‘${t}’ 이야기를 해 주셨죠. 그 뒤로 어떻게 되셨어요?`,
      `요즘도 ‘${t}’ 이야기가 생각나세요? 근황을 들려주세요.`,
    ],
  };
  const list = lists[m.category];
  return list[variant % list.length];
}

export function templateRecallQuestion(m: Memory): string {
  const custom = m.tags.map((t) => CUSTOM[t]).find(Boolean);
  if (custom) return custom[m.recallCount % custom.length](placePrefix(m));
  return generic(m, m.recallCount);
}

